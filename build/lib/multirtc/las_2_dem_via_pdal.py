def fill_dem(input_dem, filled_dem):
    # Open the DTM generated by PDAL
    with rasterio.open(input_dem) as src:
        image = src.read(1)  # Read the first band
        profile = src.profile
        nodata_val = src.nodata

        # Create a mask for nodata values
        mask = image == nodata_val

        # Fill nodata values
        filled_image = fillnodata(image, mask=~mask, max_search_distance=100, smoothing_iterations=0)

    # Update profile for output
    profile.update(nodata=None)  # Remove nodata value from profile if desired

    # Write the filled DTM to a new file
    with rasterio.open(filled_dem, 'w', **profile) as dst:
        dst.write(filled_image, 1)

    print('Nodata values filled and saved to filled_dtm.tif')


