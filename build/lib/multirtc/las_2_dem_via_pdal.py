def get_las_crs(input_las_file):
    pipeline_obj = [{'type': 'readers.las', 'filename': input_las_file}]

    pipeline_json = json.dumps(pipeline_obj)

    pipeline = pdal.Pipeline(pipeline_json)

    # Execute the pipeline to load the metadata
    pipeline.execute()
    # Access the metadata
    metadata = pipeline.metadata

    try:
        # This might vary depending on how the CRS is stored in your LAS file
        # You may need to parse the WKT or look for a specific 'epsg' key
        # within the 'spatialreference' or 'srs' dictionary.
        # For demonstration, let's assume an 'epsg' key might exist directly:
        epsg_code = metadata['readers.las'][0]['spatialreference']['epsg']
        print(f'CRS (EPSG): {epsg_code}')
        return epsg_code

    except KeyError:
        print('EPSG code not found in expected location.')
        return None


